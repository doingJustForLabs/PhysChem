import numpy as np
from scipy.stats import linregress
import matplotlib.pyplot as plt

# Экспериментальные данные из изображения
# t, с (CH3COOC2H5), моль/л
time_data = np.array([0, 178, 273, 531, 866, 1510, 1918, 2401])  # секунды
concentration_data = np.array([0.00980, 0.00892, 0.00864, 0.00792, 0.00724, 0.00646, 0.00603, 0.00574])  # моль/л

# Начальная концентрация
C0 = concentration_data[0]

# --- Определение порядка реакции ---

# Проверка первого порядка: ln(C) от t
ln_C = np.log(concentration_data)
slope_1, intercept_1, r_value_1, p_value_1, std_err_1 = linregress(time_data, ln_C)
r_squared_1 = r_value_1**2

# Проверка второго порядка: 1/C от t
inv_C = 1 / concentration_data
slope_2, intercept_2, r_value_2, p_value_2, std_err_2 = linregress(time_data, inv_C)
r_squared_2 = r_value_2**2

print("--- Определение порядка реакции ---")
print(f"Аппроксимация первого порядка (ln(C) от t):")
print(f"- Коэффициент детерминации (R-квадрат): {r_squared_1:.6f}")
print(f"  Наклон (должен быть -k): {slope_1:.6f}")
print(f"  Пересечение (должно быть ln(C0)): {intercept_1:.6f} (Фактическое ln(C0): {np.log(C0):.6f})")

print(f"\nАппроксимация второго порядка (1/C от t):")
print(f"- Коэффициент детерминации (R-квадрат): {r_squared_2:.6f}")
print(f"  Наклон (должен быть k): {slope_2:.6f}")
print(f"  Пересечение (должно быть 1/C0): {intercept_2:.6f} (Фактическое 1/C0: {1/C0:.6f})")

# Определяем порядок на основе значения R-квадрат.
# Реакция CH3COOC2H5 + NaOH обычно является реакцией второго порядка в целом.
# Если начальные концентрации равны, d[A]/dt = -k[A]^2, поэтому график 1/[A] от t линеен.
# Если [NaOH] >> [CH3COOC2H5], это псевдо-первый порядок по CH3COOC2H5, график ln[A] от t линеен.
# Мы выбираем тот, у которого R-квадрат ближе к 1.

reaction_order = None
k = None

# Выбираем порядок на основе R-квадрат, отдавая предпочтение второму порядку,
# если он хорошо описывает данные (R^2 > 0.98), так как это типично для омыления.
if r_squared_2 > 0.98: # Предпочтение второму порядку, если аппроксимация очень хорошая
    reaction_order = 2
    k = slope_2  # Для второго порядка наклон равен k
    print(f"\nРеакция, вероятно, второго порядка по CH3COOC2H5 (или второго порядка в целом при равных начальных концентрациях).")
    print(f"Константа скорости (k) = {k:.4f} л/(моль·с)")
elif r_squared_1 > r_squared_2 and r_squared_1 > 0.98: # Если первый порядок значительно лучше и хорош
    reaction_order = 1
    k = -slope_1 # Для первого порядка наклон равен -k
    print(f"\nРеакция, вероятно, псевдо-первого порядка по CH3COOC2H5.")
    print(f"Константа скорости (k') = {k:.4e} 1/с")
else: # Если ни один из порядков не дает очень хорошей аппроксимации или R-квадраты близки, выбираем лучший
    if r_squared_2 > r_squared_1:
        reaction_order = 2
        k = slope_2
        print(f"\nСудя по значениям R-квадрат ({r_squared_2:.4f} для второго порядка против {r_squared_1:.4f} для первого), реакция ближе к кинетике второго порядка.")
        print(f"Константа скорости (k) = {k:.4f} л/(моль·с)")
        print(f"  (Используется график 1/C от t, где наклон = k)")
    else:
        reaction_order = 1
        k = -slope_1
        print(f"\nСудя по значениям R-квадрат ({r_squared_1:.4f} для первого порядка против {r_squared_2:.4f} для второго), реакция ближе к кинетике первого порядка.")
        print(f"Константа скорости (k) = {k:.4e} 1/с")
        print(f"  (Используется график ln(C) от t, где наклон = -k)")


# --- Расчет периода полураспада (t_1/2) ---
print("\n--- Расчет периода полураспада ---")
if reaction_order is not None and k is not None and k > 0:
    if reaction_order == 1:
        t_half = np.log(2) / k
        print(f"Период полураспада (t_1/2) для реакции первого порядка = {t_half:.2f} с")
    elif reaction_order == 2:
        # Для A + B -> P, если [A0] = [B0], то t_1/2 = 1 / (k * C0_A)
        # Или для 2A -> P, t_1/2 = 1 / (k * C0_A)
        # Мы предполагаем, что это так для CH3COOC2H5 на основе графика 1/C.
        t_half = 1 / (k * C0)
        print(f"Период полураспада (t_1/2) для реакции второго порядка = {t_half:.2f} с")
    else:
        print(f"Период полураспада для порядка {reaction_order} не рассчитывается данным скриптом.")
else:
    print("Невозможно рассчитать период полураспада: порядок реакции или константа скорости не определены корректно.")

# --- Расчет концентрации и степени превращения при t = 2600 с ---
t_specific = 2600  # секунд

print(f"\n--- Расчеты при t = {t_specific} с ---")
if reaction_order is not None and k is not None and k > 0:
    if reaction_order == 1:
        C_at_t = C0 * np.exp(-k * t_specific)
        conversion = (C0 - C_at_t) / C0
        print(f"Концентрация CH3COOC2H5 при {t_specific} с = {C_at_t:.6f} моль/л")
        print(f"Степень превращения (X) при {t_specific} с = {conversion:.4f} или {conversion*100:.2f}%")
    elif reaction_order == 2:
        # 1/C(t) = 1/C0 + kt
        C_at_t = 1 / (1/C0 + k * t_specific)
        conversion = (C0 - C_at_t) / C0
        print(f"Концентрация CH3COOC2H5 при {t_specific} с = {C_at_t:.6f} моль/л")
        print(f"Степень превращения (X) при {t_specific} с = {conversion:.4f} или {conversion*100:.2f}%")
    else:
        print(f"Невозможно рассчитать концентрацию и степень превращения для порядка {reaction_order}.")
else:
    print("Невозможно рассчитать концентрацию и степень превращения: порядок реакции или константа скорости не определены корректно.")


# --- Построение графиков для визуальной проверки (необязательно) ---
plt.figure(figsize=(12, 5))

plt.subplot(1, 2, 1)
plt.plot(time_data, ln_C, 'o', label='Экспериментальные ln(C)')
plt.plot(time_data, intercept_1 + slope_1 * time_data, '-', label=f'Аппроксимация первого порядка\nR²={r_squared_1:.4f}')
plt.xlabel('Время (с)')
plt.ylabel('ln(C)')
plt.title('Проверка кинетики первого порядка')
plt.legend()
plt.grid(True)

plt.subplot(1, 2, 2)
plt.plot(time_data, inv_C, 'o', label='Экспериментальные 1/C')
plt.plot(time_data, intercept_2 + slope_2 * time_data, '-', label=f'Аппроксимация второго порядка\nR²={r_squared_2:.4f}')
plt.xlabel('Время (с)')
plt.ylabel('1/C (л/моль)')
plt.title('Проверка кинетики второго порядка')
plt.legend()
plt.grid(True)

plt.tight_layout()
plt.show()

print("\nПримечание: Текст задачи подразумевает определение 'порядка' реакции и константы скорости.")
print("Омыление сложного эфира NaOH обычно является реакцией второго порядка в целом (первый порядок по эфиру и первый порядок по NaOH).")
print("Если начальные концентрации эфира и NaOH равны, интегрированный закон скорости для эфира имеет вид 1/C = 1/C0 + kt.")
print("Если NaOH находится в большом избытке, реакция может быть псевдо-первого порядка по эфиру.")
print("Код выбрал порядок на основе наилучшего значения R-квадрат из предоставленных данных для CH3COOC2H5.")