"""Вариант 23"""

from Lab12.classes.nasa import nasa_db
from Lab12.classes.reaction import Reaction
from Lab12.classes.substance import Substance


r = Reaction("2H20(г) + 2Cl2 => 4HCl + O2")

T = 298

nasa_db.add_NASA_data(
    [
        "H20(г) 0.41986352E+01 -0.20364017E-02 0.65203416E-05 -0.54879269E-08 0.17719680E-11 -0.30293726E+05 -0.84900901E+00",
        "Cl2 2.73638114E+00 7.83525699E-03 -1.45104963E-05 1.25730834E-08 -4.13247143E-12 -1.05880114E+03 9.44557148E+00",
        "HCl 0.34637647E+01 0.47648423E-03 -0.20030122E-05 0.33171437E-08 -0.14495818E-11 -0.12144352E+05 0.26642828E+01",
        "O2 0.03212936E+02 0.01127486E-01 -0.05756150E-05 0.01313877E-07 -0.08768554E-11 -0.01005249E+05 0.06034738E+02",
    ]
)


if __name__ == "__main__":
    print(f"Реакция: {r}")

    enthalpy = r.get_enthalpy(T)

    print(f"Энтальпия реакции: {enthalpy / 1000:.4f} кДж/Моль\n")

    # Расчитываем число молей газа
    delta_v = 0
    for reagent in r.get_reagents:
        delta_v -= Substance(reagent).find_substance_coefficient()[0]

    for product in r.get_products:
        delta_v += Substance(product).find_substance_coefficient()[0]

    print("Выводы:")

    # а) Повышение температуры
    if enthalpy > 0:
        print(
            "а) Реакция эндотермическая (поглощает тепло). Повышение температуры смещает равновесие вправо (к продуктам)."
        )
        temp_effect = "повышать"
    elif enthalpy < 0:
        print(
            "а) Реакция экзотермическая (выделяет тепло). Повышение температуры смещает равновесие влево (к реагентам)."
        )
        temp_effect = "понижать"
    else:
        print("а) Реакция теплово нейтральна. Температура не влияет на равновесие.")
        temp_effect = "оставлять нейтральной"

    # б) Повышение давления
    if delta_v < 0:
        print(
            "б) Повышение давления смещает равновесие в сторону меньшего объёма (вправо)."
        )
        pressure_effect = "повышенном"
    elif delta_v > 0:
        print(
            "б) Повышение давления смещает равновесие в сторону меньшего числа молей газа (влево)."
        )
        pressure_effect = "пониженном"
    else:
        print("б) Количество молей газа не меняется. Давление не влияет на равновесие.")
        pressure_effect = "любом"

    # в) Добавление инертного газа
    print("в) Добавление инертного газа при постоянном объёме не влияет на равновесие.")

    # Вывод общих рекомендаций
    print("\nРекомендации по условиям проведения реакции:")
    if enthalpy == 0 and delta_v == 0:
        print(
            "Проводить реакцию можно при любых значениях температуры и давления — равновесие не зависит от них."
        )
    else:
        print(f"— Температура: для увеличения выхода температуру нужно {temp_effect}.")
        print(f"— Давление: рекомендуется проводить при {pressure_effect} давлении.")
